# simple validator based on SQL column types generated by the framework
def _validate_data(data, columns):
    """Validate dict 'data' against columns mapping like {'col': {'type': 'INTEGER'|'TEXT', ...}}.
    Returns (True, None) on success or (False, error_message) on failure.
    Supports optional constraints: max_length for TEXT, min/max for INTEGER.
    """
    for k, v in (data or {}).items():
        col_meta = columns.get(k)
        if not col_meta:
            # unknown column: accept (generator controls schema) or reject
            continue
        # allow older simple string mapping
        if isinstance(col_meta, str):
            t = col_meta.upper()
            meta = {}
        else:
            t = col_meta.get('type', '').upper()
            meta = dict(col_meta)
        if 'INTEGER' in t:
            try:
                iv = int(v)
            except Exception:
                return False, f"column {k} expects integer"
            if 'min' in meta and iv < meta['min']:
                return False, f"column {k} min is {meta['min']}"
            if 'max' in meta and iv > meta['max']:
                return False, f"column {k} max is {meta['max']}"
        elif 'TEXT' in t:
            try:
                s = str(v)
            except Exception:
                return False, f"column {k} expects text"
            if 'max_length' in meta and len(s) > meta['max_length']:
                return False, f"column {k} max_length is {meta['max_length']}"
        # extend with other SNMP-specific validations as needed
    return True, None


