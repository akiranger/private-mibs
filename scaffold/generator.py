def _snmp_type_to_sql(snmp_type):
    t = (snmp_type or '').lower()
    # integer-like types
    if 'counter64' in t or 'integer' in t or 'int' in t or 'unsigned' in t:
        return 'INTEGER'
    # text / octet types
    if 'octet' in t or 'string' in t or 'oid' in t:
        return 'TEXT'
    # counters / gauges are numeric
    if 'counter' in t or 'timeticks' in t or 'gauge' in t:
        return 'INTEGER'
    return 'TEXT'


def _parse_snmp_syntax(snmp_syntax):
    """Extract base type and simple constraints from an SNMP SYNTAX string.

    Returns (base_type_str, constraints_dict). Examples handled:
      'OCTET STRING (SIZE (0..64))' -> ('OCTET STRING', {'max_length': 64})
      'INTEGER (0..255)' -> ('INTEGER', {'min':0, 'max':255})
    This is heuristic and supports common pysmi-style strings.
    """
    if not snmp_syntax:
        return None, {}
    s = str(snmp_syntax)
    # try to capture SIZE(n) or SIZE(m..n)
    import re
    constraints = {}
    m = re.search(r'SIZE\s*\(\s*(\d+)(?:\.\.(\d+))?\s*\)', s, re.IGNORECASE)
    if m:
        # if range, use upper bound as max_length; else use single value
        if m.group(2):
            constraints['max_length'] = int(m.group(2))
        else:
            constraints['max_length'] = int(m.group(1))
    # INTEGER range like (min..max)
    m2 = re.search(r'INTEGER\s*\(\s*(-?\d+)\s*\.\.\s*(-?\d+)\s*\)', s, re.IGNORECASE)
    if m2:
        constraints['min'] = int(m2.group(1))
        constraints['max'] = int(m2.group(2))
    # fallback: try to capture a parenthesized range for generic types
    m3 = re.search(r'\(\s*(-?\d+)\s*\.\.\s*(-?\d+)\s*\)', s)
    if m3 and 'min' not in constraints:
        try:
            constraints['min'] = int(m3.group(1))
            constraints['max'] = int(m3.group(2))
        except Exception:
            pass
    # base type: strip trailing constraint parentheses
    base = re.sub(r'\(.*\)', '', s).strip()
    return base, constraints


def generate_handlers(schema_path, outdir):
    with open(schema_path, 'r', encoding='utf-8') as f:
        schema = json.load(f)
    os.makedirs(outdir, exist_ok=True)
    mib = os.path.splitext(os.path.basename(schema_path))[0]

    # Helper: find entry definition by name
    entries = {o.get('name'): o for o in schema.get('objects', []) if o.get('kind') in ('entry','table','scalar','column')}

    for obj in schema.get('objects', []):
        name = obj.get('name', 'unknown')
        # sanitize name to be filename-friendly
        safe_name = ''.join(c if c.isalnum() or c=='_' else '_' for c in name)
        is_scalar = (obj.get('kind') == 'scalar')
        columns = {}
        unique_cols = None
        if obj.get('kind') == 'table' and obj.get('entry_type'):
           entry = entries.get(obj.get('entry_type'))
           if entry and entry.get('fields'):
               for f in entry.get('fields'):
                   col_name = f.get('name')
                   syntax = f.get('type')
                   base, constraints = _parse_snmp_syntax(syntax)
                   sql_type = _snmp_type_to_sql(base or syntax)
                   if constraints:
                       meta = {'type': sql_type}
                       meta.update(constraints)
                       columns[col_name] = meta
                   else:
                       columns[col_name] = sql_type
               # ensure id primary key
               columns = {'id': 'INTEGER PRIMARY KEY AUTOINCREMENT', **columns}
               # Heuristic: collect any field whose name suggests an index (contains 'Index' or endswith 'index')
               index_fields = []
               for f in entry.get('fields') or []:
                   fname = f.get('name')
                   if not fname:
                       continue
                   if 'Index' in fname or fname.lower().endswith('index') or 'index' == fname.lower():
                       index_fields.append(fname)
               if index_fields:
                   unique_cols = index_fields
           else:
               # generic table
               columns = {'id': 'INTEGER PRIMARY KEY AUTOINCREMENT', 'value': 'TEXT', 'updated_at': 'TEXT'}
        elif obj.get('kind') == 'entry' and obj.get('fields'):
            # entry as standalone table
            cols = {}
            for f in obj.get('fields'):
                syntax = f.get('type')
                base, constraints = _parse_snmp_syntax(syntax)
                sql_type = _snmp_type_to_sql(base or syntax)
                if constraints:
                    meta = {'type': sql_type}
                    meta.update(constraints)
                    cols[f.get('name')] = meta
                else:
                    cols[f.get('name')] = sql_type
            columns = {'id': 'INTEGER PRIMARY KEY AUTOINCREMENT', **cols}
            is_scalar = False
            # heuristic for unique_cols for entries
            first_field = obj.get('fields')[0].get('name') if obj.get('fields') else None
            if first_field and ('Index' in first_field or first_field.lower().endswith('index')):
                unique_cols = [first_field]
        else:
            # scalar or unknown -> single-value table
            columns = {'value': 'TEXT', 'updated_at': 'TEXT'}
            is_scalar = True

        # Render Python literal for columns mapping; support dict values for metadata
        cols_items = []
        for k, v in columns.items():
            if isinstance(v, str):
                cols_items.append(f"'{k}': '{v}'")
            else:
                cols_items.append(f"'{k}': {repr(v)}")
        cols_literal = '{' + ', '.join(cols_items) + '}'
        # integer columns for validation
        integer_cols = [k for k, v in columns.items() if 'INT' in v.upper()]
        if integer_cols:
            integer_literal = '[' + ', '.join(f"'{c}'" for c in integer_cols) + ']'
        else:
            integer_literal = '[]'
        if unique_cols:
            unique_literal = '[' + ', '.join(f"'{c}'" for c in unique_cols) + ']'
        else:
            unique_literal = 'None'

        fname = os.path.join(outdir, f'{safe_name}.py')
        with open(fname, 'w', encoding='utf-8') as fh:
            # Use simple literal replacements to avoid str.format parsing embedded dict braces
            out = HANDLER_TMPL
            out = out.replace('{name}', safe_name)
            out = out.replace('{columns}', cols_literal)
            out = out.replace('{is_scalar}', str(is_scalar))
            out = out.replace('{unique_cols}', unique_literal)
            out = out.replace('{oid_base}', 'None')
            out = out.replace('{integer_cols}', integer_literal)
            fh.write(out)

    # If no objects, create a placeholder
    if not schema.get('objects'):
        with open(os.path.join(outdir, f'{mib}_placeholder.py'), 'w', encoding='utf-8') as fh:
            out = HANDLER_TMPL
            out = out.replace('{name}', 'placeholder')
            out = out.replace('{columns}', "{'value':'TEXT','updated_at':'TEXT'}")
            out = out.replace('{is_scalar}', 'True')
            out = out.replace('{unique_cols}', 'None')
            out = out.replace('{oid_base}', 'None')
            out = out.replace('{integer_cols}', '[]')
            fh.write(out)


if __name__ == '__main__':
    if len(sys.argv) < 3:
        print('Usage: python generator.py schema.json outdir', file=sys.stderr)
        sys.exit(2)
    generate_handlers(sys.argv[1], sys.argv[2])
